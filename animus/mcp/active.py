"""Active Context Injector — makes Animus proactive and autonomous.

This module provides:
1. Auto-collection on file changes (real-time indexing)
2. Workspace instructions auto-generation with context summaries
3. Autonomous sync daemon with smart scheduling
4. Pre-built prompt context for common scenarios
"""

from __future__ import annotations

import json
import logging
import re
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

from ..config import AnimusConfig
from ..indexer.engine import IndexEngine

logger = logging.getLogger("animus.active")


class ActiveContextInjector:
    """Proactive memory system that auto-surfaces relevant context.

    Workflows:
    1. On workspace open → generate .animus-context.md with recent memories
    2. On file save → auto-index and find related memories
    3. Periodically → update workspace instruction overlays
    4. On sync → merge cross-machine context
    """

    def __init__(self, config: AnimusConfig):
        self.config = config
        self.config.ensure_dirs()
        self.engine = IndexEngine(config.db_path)

    def generate_workspace_context(self, workspace_root: Path) -> str:
        """Generate a .animus-context.md file for the current workspace.

        This file is auto-included by Copilot as workspace context,
        providing relevant memories from past sessions.
        """
        workspace_name = workspace_root.name
        stats = self.engine.stats_view()

        # Get recent memories for this workspace
        recent = self._get_workspace_memories(workspace_name, limit=15)
        cross_machine = self._get_cross_machine_memories(workspace_name, limit=10)

        # Build context document
        lines = [
            "<!-- Auto-generated by Animus — DO NOT EDIT -->",
            "<!-- This file provides context from past Copilot interactions -->",
            "",
            "# Animus Context",
            "",
            f"Node: {self.config.node_id} ({self.config.node_name})",
            f"Workspace: {workspace_name}",
            f"Total memories: {stats['total_memories']}",
            f"Statistics: {stats['stats_status']} (age seconds: {stats['stats_age_seconds']})",
            f"Last updated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}",
            "",
        ]

        if recent:
            lines.append("## Recent Memories (this workspace)")
            lines.append("")
            for mem in recent:
                title = mem.get("title", "")[:60]
                mtype = mem.get("type", "")
                ts = mem.get("timestamp", "")[:16]
                content = mem.get("content", "")[:200].replace("\n", " ")
                lines.append(f"- **{title}** ({mtype}, {ts})")
                lines.append(f"  {content}")
                lines.append("")

        if cross_machine:
            lines.append("## Cross-Machine Context (from other nodes)")
            lines.append("")
            for mem in cross_machine:
                title = mem.get("title", "")[:60]
                node = mem.get("source_node", "")
                content = mem.get("content", "")[:200].replace("\n", " ")
                lines.append(f"- **{title}** (node: {node})")
                lines.append(f"  {content}")
                lines.append("")

        # Key decisions and patterns
        decisions = self._get_key_decisions(workspace_name, limit=5)
        if decisions:
            lines.append("## Key Decisions & Patterns")
            lines.append("")
            for mem in decisions:
                lines.append(f"- {mem.get('content', '')[:300]}")
                lines.append("")

        return "\n".join(lines)

    def write_workspace_context(self, workspace_root: Path) -> Path:
        """Write the context file and return its path."""
        content = self.generate_workspace_context(workspace_root)
        ctx_file = workspace_root / ".animus-context.md"
        ctx_file.write_text(content, encoding="utf-8")
        logger.info("Wrote workspace context: %s", ctx_file)
        return ctx_file

    def generate_copilot_instructions_overlay(self, workspace_root: Path) -> str:
        """Generate content to append to copilot-instructions.md.

        This gives Copilot awareness of what Animus knows about the project.
        """
        workspace_name = workspace_root.name
        stats = self.engine.stats_view()

        lines = [
            "",
            "## Animus Memory Context",
            "",
            "This workspace has the Animus MCP server active. Use the following tools:",
            "- `animus_recall` — Get past context relevant to the current conversation",
            "- `animus_search` — Search all past interactions across machines",
            "- `animus_remember` — Save important decisions/solutions for future recall",
            "- `animus_context` — Get file-specific context",
            "- `animus_timeline` — See recent activity timeline",
            "- `animus_session_list` — Find which Copilot session a piece of work happened in",
            "- `animus_session` — Replay an entire conversation by id (full transcript, paged)",
            "- `animus_related` — Walk previous/next/sibling turns around any memory",
            "- `animus_neural_map` — See workspace × session graph with tag-bridged edges",
            "",
            f"Memories available: {stats['total_memories']} across {stats['unique_nodes']} machines.",
            f"Statistics: {stats['stats_status']} (age seconds: {stats['stats_age_seconds']})",
            "",
            "When working on complex tasks, ALWAYS use `animus_recall` first to check if ",
            "similar problems have been solved before. When making important decisions, ",
            "use `animus_remember` to persist them for future reference.",
            "",
        ]

        return "\n".join(lines)

    def get_active_context_for_query(self, query: str, workspace: str = "") -> str:
        """Get pre-built context to inject into a Copilot prompt.

        Used by the MCP server to provide autonomous context injection.
        """
        from ..mcp.rag import RAGEngine
        rag = RAGEngine(self.engine)
        results = rag.contextual_recall(query, workspace=workspace, max_tokens=1500)

        if not results:
            return ""

        lines = ["[Animus Context — relevant memories from past interactions]", ""]
        for r in results:
            lines.append(f"• {r.get('title', '')}: {r.get('content', '')[:200]}")
        lines.append("[End Animus Context]")

        return "\n".join(lines)

    # ── Internal Queries ──

    def _get_workspace_memories(self, workspace: str, limit: int = 15) -> list[dict]:
        """Get recent memories for a specific workspace."""
        rows = self.engine.conn.execute(
            "SELECT * FROM memories WHERE workspace = ? ORDER BY timestamp DESC LIMIT ?",
            (workspace, limit),
        ).fetchall()
        return [dict(r) for r in rows]

    def _get_cross_machine_memories(self, workspace: str, limit: int = 10) -> list[dict]:
        """Get memories from other machines for this workspace."""
        rows = self.engine.conn.execute(
            """SELECT * FROM memories
               WHERE workspace = ? AND source_node != ?
               ORDER BY timestamp DESC LIMIT ?""",
            (workspace, self.config.node_id, limit),
        ).fetchall()
        return [dict(r) for r in rows]

    def _get_key_decisions(self, workspace: str, limit: int = 5) -> list[dict]:
        """Find memories that look like key decisions or important patterns."""
        # Search for decision-like content
        try:
            results = self.engine.search(
                "decision pattern approach solution architecture",
                workspace=workspace,
                limit=limit,
            )
            return results
        except Exception:
            return []

    def close(self) -> None:
        self.engine.close()
